// Rewrites src/index.ts to re-export every ts-rs file in src/generated, so a
// new Rust type is importable from "@selecta/protocol" without a manual edit.
import { readdirSync, writeFileSync } from "node:fs";
const dir = new URL("./src/generated/", import.meta.url);
const names = readdirSync(dir).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)).sort();
writeFileSync(new URL("./src/index.ts", import.meta.url), "// Generated by gen-index.mjs (npm run protocol). Do not edit.\n" + names.map((n) => `export type { ${n} } from "./generated/${n}";`).join("\n") + "\n");
console.log(`protocol: ${names.length} types`);
